import {createRequire} from 'node:module';
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const require=createRequire(path.join(process.env.APPS_SCRIPT_TOOL_ROOT || root,'package.json'));
const {build}=require('esbuild');
const pbkdf2=require.resolve('@noble/hashes/pbkdf2.js');
const sha2=require.resolve('@noble/hashes/sha2.js');
const utils=require.resolve('@noble/hashes/utils.js');
await build({
  stdin:{contents:`export {pbkdf2} from ${JSON.stringify(pbkdf2)};export {sha256} from ${JSON.stringify(sha2)};export {hexToBytes,bytesToHex} from ${JSON.stringify(utils)};`,resolveDir:root},
  bundle:true,format:'iife',globalName:'LoginCrypto',platform:'neutral',target:'es2020',minify:true,
  outfile:path.join(root,'Crypto.gs'),
  banner:{js:'// Bundled @noble/hashes 2.4.0 (MIT). See THIRD_PARTY_LICENSE.txt. Generated by tools/build-crypto.mjs.'},
});
fs.copyFileSync(path.join(path.dirname(sha2),'LICENSE'),path.join(root,'THIRD_PARTY_LICENSE.txt'));
console.log('Built Apps Script-compatible password crypto bundle.');
